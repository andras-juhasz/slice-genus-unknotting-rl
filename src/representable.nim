proc to_seq*[T](self: RepresentableState[T]): seq[(string, Tensor[float])] =
    discard """
    Converts self to a sequence of tensors by
    - Joining the values of the mutable features (band
      path, total twists and band matrix) with the
      pre-computed values of the immutable features (PD
      code, Gauss code, etc.)
    - Returning the list of (feature name, feature value)
      pairs

    Returns:
        A sequence of tensors representing self.
    """
    var truncated_band_path = collect:
        for t in self.band_path:
            t[0 ..< 3]
    var band_path = pad(if truncated_band_path.len > 0: truncated_band_path.toTensor() else: zeros[int]([0, 3]),
                        [2*self.shape[0], 3], -1000)
    var twists = collect:
        for t in self.band_path:
            t[3]
    var total_twists = sum(twists)
    var band_matrix = newTensorWith([self.link.crossings.len, 4], -10)
    for band_node in self.band_path:
        band_matrix[band_node[0], band_node[1]] = band_node[2]
    band_matrix = pad(band_matrix, [self.shape[0], 4], -1000)
    return @[
        ("band_path", band_path.astype(float)),
        ("total_twists", [float(total_twists)].toTensor()),
        ("band_matrix", band_matrix.astype(float))
    ] & self.features

proc mdp_to_seq*[T](self: RepresentableState[T]): seq[(string, Tensor[float])] =
    discard """
    Converts to tensors the part of the state that to_seq
    leaves out although the legal actions, the next state
    or the reward depend on it: the twists of every band
    segment, row by row with band_path, the crossing
    number of the simplified link and, for band moves, the
    connected component label (CCL) of every link
    component, one genera_info row per CCL and the current
    genus.

    The genera_info rows are sorted by CCL.
    
    Returns:
        A sequence of (feature name, feature value) pairs.
    """
    var twists = collect:
        for t in self.band_path:
            t[3]
    var features = @[
        ("band_twists",
         pad(if twists.len > 0: twists.toTensor() else: zeros[int]([0]),
             [1, 2*self.shape[0]], -1000).reshape(2*self.shape[0]).astype(float)),
        ("simplified_num_crossings",
         [float(self.simplified_link.crossings.len)].toTensor())
    ]
    when T is BandMove:
        var ccls = collect:
            for comp in self.link.link_components:
                comp.extra_info
        var labels = collect:
            for ccl in self.framework_info.genera_info.keys:
                ccl
        labels.sort()
        var rows = collect:
            for ccl in labels[0 ..< min(labels.len, self.shape[1])]:
                let gi = self.framework_info.genera_info[ccl]
                @[ccl, gi.num_end_actions, gi.num_init_comps,
                  gi.num_curr_comps, gi.num_orig_comps]
        features &= @[
            ("component_ccl",
             pad(if ccls.len > 0: ccls.toTensor() else: zeros[int]([0]),
                 [1, self.shape[1]], -1000).reshape(self.shape[1]).astype(float)),
            ("genera_info",
             pad(if rows.len > 0: rows.toTensor() else: zeros[int]([0, 5]),
                 [self.shape[1], 5], -1000).astype(float)),
            ("current_genus",
             [float(BandMove(self).compute_current_answer(self.link, 0))].toTensor())
        ]
    return features

method next_state*(
    self: CrossChangeState,
    action: string
): CrossChangeState {.base.} =
    var base_inst = CrossChange(self).next_state(action)
    var features: seq[(string, Tensor[float])]
    if get_act_type(action) == "end":
        features = compute_features(
            base_inst, self.shape, self.features_cls
        )
    else:
        features = self.features
    return representablestate_from_base_state(
        base_inst, self.shape, self.features_cls, features
    )

method next_state*(
    self: BandMoveState,
    action: string
): BandMoveState {.base.} =
    var base_inst = BandMove(self).next_state(action)
    var features: seq[(string, Tensor[float])]
    # a birth changes the diagram too (the birthed unknot is
    # joined into it), so the features must be recomputed
    if get_act_type(action) in ["end", "birth"]:
        features = compute_features(
            base_inst, self.shape, self.features_cls
        )
    else:
        features = self.features
    return representablestate_from_base_state(
        base_inst, self.shape, self.features_cls, features
    )

proc cls_name*[T](self: RepresentableState[T]): string =
    return &"RepresentableState<{T(self).cls_name()}>"

proc `$`*[T](obj: RepresentableState[T]): string =
    var features_cls_str = collect:
        for c in obj.features_cls:
            c.cls_name()
    return &"{T(obj)}shape={obj.shape}\nadditional feature classes={features_cls_str}\nfeature values={obj.features}\n"

