proc crosschangestate_action_masks*(
    obj: CrossChangeState
): seq[bool] {.exportpy.} =
    var mask = newSeq[bool](obj.shape[0] * 20 + 2)
    if obj.band_path.len == 0:
        for c in 0 ..< obj.link.crossings.len:
            for s in 0 ..< 4:
                mask[(c*4 + s)*5] = true
    else:
        let cur_strand = (obj.band_path[obj.band_path.len-1][0],
                          obj.band_path[obj.band_path.len-1][1])
        for (c, s) in obj.feasible_next_strands(cur_strand):
            if not obj.check_over_under_error(c, s):
                mask[(c*4 + s)*5 + 1] = true
                mask[(c*4 + s)*5 + 2] = true
            if not obj.check_end_errors(c, s):
                mask[(c*4 + s)*5 + 3] = true
                mask[(c*4 + s)*5 + 4] = true
        for (i, sign) in [(0, 1), (1, -1)]:
            if not obj.check_twist_error(sign):
                mask[obj.shape[0]*20 + i] = true
    return mask

proc bandmovestate_action_masks*(
    obj: BandMoveState
): seq[bool] {.exportpy.} =
    # the slice frameworks have one extra action at the last
    # index: unknot_birth, legal exactly while no band is in
    # progress (mirrors check_birth_error); the mask length
    # must match the env's action count
    let has_birth = obj.framework in ["slice", "strong slice"]
    var mask = newSeq[bool](obj.shape[0] * 24 + (if has_birth: 3 else: 2))
    if obj.band_path.len == 0:
        for c in 0 ..< obj.link.crossings.len:
            for s in 0 ..< 4:
                mask[(c*4 + s)*5] = true
        if has_birth:
            mask[obj.shape[0]*24 + 2] = true
    else:
        let cur_strand = (obj.band_path[obj.band_path.len-1][0],
                          obj.band_path[obj.band_path.len-1][1])
        for (c, s) in obj.feasible_next_strands(cur_strand):
            if not obj.check_over_under_error(c, s):
                mask[(c*4 + s)*5 + 1] = true
                mask[(c*4 + s)*5 + 2] = true
            if not obj.check_end_error(c, s, 0):
                mask[obj.shape[0]*20 + 2 + (c*4 + s)] = true
            if not obj.check_end_error(c, s, 1):
                mask[(c*4 + s)*5 + 3] = true
            if not obj.check_end_error(c, s, -1):
                mask[(c*4 + s)*5 + 4] = true
        for (i, sign) in [(0, 1), (1, -1)]:
            if not obj.check_twist_error(sign):
                mask[obj.shape[0]*20 + i] = true
    return mask

proc nim_rand_state*(): string {.exportpy.} =
    var s = newStringStream("")
    store(s, randState())
    s.setPosition(0)
    return s.readAll()

proc nim_randomize*(): void {.exportpy.} =
    randomize()

proc nim_set_seed*(seed: int): void {.exportpy.} =
    discard """
    Seeds the random number generator of this compiled
    module, which the transitions (through the
    simplification of spherogram-nim) and the random walk
    steps of the mixed agent draw from. agent.so and
    representable.so each hold their own generator, so a
    process using both seeds both.

    Args:
        seed: a positive integer; equal seeds give equal
            random streams

    Raises:
        ValueError: if seed is not positive
    """
    if seed <= 0:
        raise newException(ValueError, &"seed {seed} is not positive")
    randomize(seed)

