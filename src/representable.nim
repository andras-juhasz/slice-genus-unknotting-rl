proc nim_set_random_state*(state_str: string): void {.exportpy.} =
    # Restore the Nim default RNG to a previously saved state.
    # ``state_str`` must be a string returned by ``nim_rand_state()``.
    var s = newStringStream(state_str)
    var r: Rand
    load(s, r)
    randState() = r

