proc bandmovestate_strand_ccls*(
    obj: BandMoveState
): (seq[array[0..3, int]], seq[int]) {.exportpy.} =
    discard """
    Gives the connected component label (CCL) of the
    surface component on which each crossing strand of
    the state's link lies, and the CCLs of the link's
    unlinked unknot components. verify_band_paths.py
    reads these labels to tell surface components apart
    and recomputes the genus itself, without genera_info.

    Returns:
        A pair: for each crossing, in order, the CCLs of
        its strands 0 to 3; and the CCLs of the unlinked
        unknot components.
    """
    var strand_ccls = newSeq[array[0..3, int]]()
    for c in 0 ..< obj.link.crossings.len:
        var row: array[0..3, int]
        for s in 0 .. 3:
            row[s] = get_strand_ccl(obj.link, c, s)
        strand_ccls.add(row)
    return (strand_ccls,
            obj.framework_info.unlinked_ccl.get(newSeq[int]()))

