discard """
The error raised when the feature values of a link
cannot be computed because the link has too many
crossings or components.
"""
type DimensionExceededError* = object of ValueError

proc compute_features*[T](
    base_inst: T,
    shape: array[0..1, int],
    features_cls: seq[TensorFeature]
): seq[(string, Tensor[float])] =
    discard """
    Calculates the features describing the link (as opposed
    to describing the band path) from a CrossChange or
    BandMove instance, given the maximum shape of the link
    and a list of additional feature classes.

    Args:
        base_inst: the CrossChange or BandMove instance
            whose link's features are to be calculated
        shape: a pair of integers; shape[0] means the
            maximum number of crossings that any link
            (either given or generated by an end action) can
            have; shape[1] means the maximum number of
            components that any link in the episodes can
            have
        features_cls: a list of classes of additional
            features whose values on base_inst.link are to
            be included

    Returns:
        A list of (feature name, feature value) pairs.

    Raises:
        DimensionExceededError: if the number of crossings
            of base_inst.link exceeds shape[0] or the number
            of components of base_inst.link exceeds shape[1]
    """
    # For diagram-dependent features, use unsimplified link
    var link_for_diagram = base_inst.link
    # For topological invariants, use simplified link
    var link_for_invariants = base_inst.simplified_link
    if (link_for_diagram.crossings.len > shape[0] or
        link_for_diagram.link_components.len > shape[1]):
        raise newException(DimensionExceededError,
                           &"the observation for link {link_for_diagram} cannot be computed because the link exceeds {shape}")
    var gauss = collect:
        for comp_code in link_for_diagram.gauss_code():
            for c in comp_code & @[-500]:
                c
    # when the link is an unlink, the PD code is an empty
    # (1-dimensional) array, but the dimension of any
    # feature must be a function only of shape, so we need
    # to pad the PD code to shape (shape[0], 4)
    var pd_code = link_for_diagram.PD_code()
    var features = @[
        ("PD_code",
         pad(if pd_code.len > 0: pd_code.toTensor() else: zeros[int]([0, 4]),
             [shape[0], 4], -1000).astype(float)),
        ("unlinked_unknot_components",
         [float(link_for_diagram.unlinked_unknot_components)].toTensor()),
        ("num_link_components",
         [float(link_for_diagram.link_components.len)].toTensor()),
        ("num_connected_components",
         [float(base_inst.framework_info.num_conn_comp)].toTensor()),
        ("gauss_code",
         pad(if gauss.len > 0: gauss.toTensor() else: zeros[int]([0]),
             [1, shape[0]*2 + shape[1]], -1000).reshape(shape[0]*2 + shape[1]).astype(float))
    ]
    # the terminal state for the algebraic unknotting number
    # calculations is a knot with Alexander polynomial 1, so
    # we need to include the Alexander polynomial in the
    # observation
    if base_inst.framework == "unknotting-alg":
        features.add((
            "alexander_poly",
            pad(base_inst.framework_info.alex_poly.get().toTensor(),
                [1, shape[0]+1], -1000).reshape(shape[0]+1).astype(float)
        ))
    # crossing signs and writhe are meaningful in every framework
    features &= @[
        ("crossing_signs",
         pad(if link_for_diagram.signs.len > 0: link_for_diagram.signs.toTensor() else: zeros[int]([0]),
             [1, shape[0]], -1000).reshape(shape[0]).astype(float)),
        ("writhe",
         [float(link_for_diagram.writhe())].toTensor())
    ]
    when T is BandMove:
        # the Seifert genus is used to shape rewards in
        # ribbon / slice genera calculations, so we need to
        # include it in the observation
        when hfk_enabled:
            var floer_hom_bundle = [-1000, -1000, -1000]
            if link_for_invariants.link_components.len + link_for_invariants.unlinked_unknot_components == 1:
                var floer_hom = link_for_invariants.knot_floer_homology()
                floer_hom_bundle = [floer_hom.seifert_genus,
                                    floer_hom.nu,
                                    floer_hom.tau]
            features &= @[
                ("seifert_genus",
                 [float(floer_hom_bundle[0])].toTensor()),
                ("nu",
                 [float(floer_hom_bundle[1])].toTensor()),
                ("tau",
                 [float(floer_hom_bundle[2])].toTensor()),
            ]
    # append the values of the optional features listed in `features_cls`,
    # each evaluated on the link it asks for
    for feature_cls in features_cls:
        let link = if feature_cls.need_unsimplified_diagram(): link_for_diagram
                   else: link_for_invariants
        features &= feature_cls.from_link(link, shape)
    return features

discard """
Given a class implementing some kind of band operations on a
link, produces a subclass that can be represented by a
(string, tensor) table for use by the reinforcement learning
environment.

Args:
    T: the class implementing a type of band operations on a
        link

Returns:
    A subclass of T which implements reinforcement
    learning-related features.
"""
type RepresentableState*[T] = ref object of T
    shape*: array[0..1, int]
    features_cls*: seq[TensorFeature]
    features*: seq[(string, Tensor[float])]

proc newRepresentableState*[T](
    band_path: seq[array[0..3, int]],
    faces: seq[SubdividedFace],
    link: Link[int],
    pd_code: seq[array[0..3, int]],
    face0: seq[array[0..3, int]],
    max_twists: int,
    framework: string,
    framework_info: FrameworkInfo,
    shape: array[0..1, int],
    features_cls: seq[TensorFeature],
    features: seq[(string, Tensor[float])],
    simplification_switch: bool = true,
    simplified_link: Option[Link[int]] = none(Link[int])
): RepresentableState[T] =
    discard """
    Initializes an instance of RepresentableState with
    all the fields filled in. This method should not be
    invoked directly.

    Args:
        band_path: list of lists with four elements: the
            first two elements record the edges with
            directions of the band's travel between the
            two faces that the edge bounds (recorded as
            crossing strands) that the band has visited
            so far; a crossing strand, viewed as an
            outgoing ray from its crossing, means that
            the band has gone through the edge of the
            crossing strand from the face on the left
            side of the ray to the face on the right
            side of the ray; the third element records
            the sign (0 for start or end in the band-move
            case, 1 for over or end1 in the crossing
            change case, and -1 for under or end2 in the
            crossing change case); the fourth and final
            element records the number of twists on the
            band after going through this crossing
            strand but before going through any later
            crossing strand, which is positive if the
            twists are counterclockwise and negative if
            they are clockwise
        faces: the function mapping the index of a face
            to the current subdivision of the face by
            the band
        link: the link that the state is concerned with
        pd_code: the PD code of link; appears as the
            first element of self.features
        face0: the function mapping a crossing strand to
            the index of its first face; the first face
            of a crossing strand is defined to be the
            face on the left side of the outgoing ray of
            the crossing strand
        max_twists: the maximum number of twists that we
            can make on the band in total; needed for
            self.check_twist_error
        framework: the type of link invariant to
            calculate; "unknotting" (for the unknotting
            number) means that we allow band operations
            between strands of the same link component
            and terminate when the current link is an 
            unlink; "ribbon" and "strong ribbon" (for the
            ribbon genus and strong ribbon genus
            respectively) also terminate when the current
            link is an unlink; "strong ribbon" additionally
            restricts band moves to same-CCL strands;
            "slice" and "strong slice" are the same as the
            ribbon frameworks with the unknot_birth action
            additionally available;
            "splitting" means that we do not allow band
            operations between strands of the same link
            component and terminate when the current
            link's diagram is completely split into link
            components; "weak splitting" means that we
            allow band operations between strands of the
            same link component and terminate when the
            current link's diagram is completely split
            into link components
        framework_info: information that is only useful
            for the calculation of some link invariants;
            the number of connected components is only
            useful for the (strong and weak) splitting
            numbers, the Alexander polynomial is only useful
            for the algebraic unknotting number, the
            unlinked ccl's are only useful for the ribbon
            and slice genera, and the genera_info
            table is used for (strong) ribbon and (strong)
            slice genus calculations
        shape: a pair of integers; shape[0] means the
            maximum number of crossings that any link
            (either given or generated by an end action)
            can have; shape[1] means the maximum number
            of components that any link in the episodes
            can have
        features_cls: a list of the classes of
            additional features of the link that we are
            using
        features: a list of values of the features of
            link; see compute_features for details
    """
    var band_twist_inst = newBandTwist(
        band_path, faces, link, pd_code, face0, max_twists,
        framework, framework_info, 
        simplification_switch, simplified_link
    )
    return RepresentableState[T](
        band_path: band_twist_inst.band_path,
        faces: band_twist_inst.faces,
        link: band_twist_inst.link,
        simplified_link: band_twist_inst.simplified_link,
        pd_code: band_twist_inst.pd_code,
        face0: band_twist_inst.face0,
        max_twists: band_twist_inst.max_twists,
        framework: band_twist_inst.framework,
        framework_info: band_twist_inst.framework_info,
        simplification_switch: band_twist_inst.simplification_switch,
        shape: shape, features_cls: features_cls,
        features: features
    )

proc representablestate_from_base_state*[T](
    base_inst: T,
    shape: array[0..1, int],
    features_cls: seq[TensorFeature],
    features: seq[(string, Tensor[float])],
    simplification_switch: bool = true,
    simplified_link: Option[Link[int]] = none(Link[int])
): RepresentableState[T] =
    discard """
    Equips a T object base_inst with features and feature
    values. Since this method does not copy its
    arguments, they should not be used again after being
    passed to this method.  (This is like rvalue
    reference arguments in C++.)

    Args:
        base_inst: the T object to equip with features
        shape: a pair of integers; shape[0] means the
            maximum number of crossings that any link
            (either given or generated by an end action)
            can have; shape[1] means the maximum number
            of components that any link in the episodes
            can have
        features_cls: the list of feature classes we are
            augmenting base_inst with
        features: the list of values of the features in
            features_cls

    Returns:
        The upgraded RepresentableState object.
    """
    return newRepresentableState[T](
        base_inst.band_path, base_inst.faces,
        base_inst.link, base_inst.pd_code, base_inst.face0,
        base_inst.max_twists, base_inst.framework,
        base_inst.framework_info, shape, features_cls,
        features, 
        base_inst.simplification_switch,
        some(base_inst.simplified_link)
    )

proc representablestate_from_link*[T](
    link: Link[int],
    max_twists: int = 5,
    framework: string = "unknotting",
    shape: array[0..1, int] = [50, 4],
    features_cls: seq[TensorFeature] = @[],
    simplification_switch: bool = true
): RepresentableState[T] =
    discard """
    Constructs an instance of RepresentableState from a
    link with no band attached.

    Args:
        link: the given link
        max_twists: the maximum number of twists (across
            all the faces, either counterclockwise or
            clockwise) allowed
        framework: the type of link invariant to
            calculate; "unknotting" (for the unknotting
            number) means that we allow band operations
            between strands of the same link component
            and terminate when the current link is an 
            unlink; "ribbon" and "strong ribbon" (for the
            ribbon genus and strong ribbon genus
            respectively) also terminate when the current
            link is an unlink; "strong ribbon" additionally
            restricts band moves to same-CCL strands;
            "slice" and "strong slice" are the same as the
            ribbon frameworks with the unknot_birth action
            additionally available;
            "splitting" means that we do not allow band 
            operations between strands of the same link 
            component and terminate when the current 
            link's diagram is completely split into link
            components; "weak splitting" means that we 
            allow band operations between strands of the
            same link component and terminate when the 
            current link's diagram is completely split 
            into link components
        shape: a pair of integers; shape[0] means the
            maximum number of crossings that any link
            (either given or generated by an end action)
            can have; shape[1] means the maximum number
            of components that any link in the episodes
            can have
        features_cls: a list of the classes of
            additional features of the link that we are
            using
        simplification_switch: if true, the link is
            simplified between states; if false, the link
            is not simplified between states (but features
            and rewards are still computed on simplified
            versions)

    Returns:
        An instance of RepresentableState whose link
        equals link and whose band has not started.
    """
    when T is CrossChange:
        var base_inst = crosschange_from_link(link, max_twists,
                                              framework,
                                              none(seq[int]),
                                              simplification_switch)
    when T is BandMove:
        var base_inst = bandmove_from_link(link, max_twists,
                                           framework,
                                           none(seq[int]),
                                           simplification_switch)
    return representablestate_from_base_state(
        base_inst, shape, features_cls,
        compute_features(base_inst, shape, features_cls),
        base_inst.simplification_switch,
        some(base_inst.simplified_link)
    )

