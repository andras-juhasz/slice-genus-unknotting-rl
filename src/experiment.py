class RLParam:
    """Parameters for reinforcement learning."""
    max_actions: int
    shape: Tuple[int, int]
    max_twists: int
    gamma: float
    features_cls: List[str]
    sampling_method: str
    simplification_switch: bool
    device: str
    mdp: bool = False
    old_reward: bool = True
    # the defaults of parameters unpickled from before these
    # two existed
    reward_settings: Optional[Dict[str, float]] = None
    seed: Optional[int] = None

    def __init__(
            self,
            max_actions: int = 50,
            shape: Tuple[int, int] = (50, 4),
            max_twists: int = 5,
            gamma: float = 0.99,
            features_cls: List[str] = None,
            sampling_method: str = 'consecutive',
            simplification_switch: bool = True,
            device: str = 'cpu',
            mdp: bool = False,
            old_reward: bool = True,
            reward_settings: Optional[Dict[str, float]] = None,
            seed: Optional[int] = None
    ):
        """
        Initializes a set of parameters for reinforcement
        learning.

        Args:
            max_actions: the maximum number of actions per
                (training or testing) episode
            shape: a pair of integers; shape[0] means the
                number of crossings that any link (either
                given or generated by an end action) can
                have at most; shape[1] means the number of
                components that any link in the episodes can
                have at most
            max_twists: the maximum number of twists (across
                all the faces, either counterclockwise or
                clockwise) allowed
            gamma: the discount factor
            features_cls: a list of the classes of other
                features of the link that we are using
            sampling_method: how we choose the initial link
                and the next link from the dataset after
                an episode has ended; "consecutive" means
                that we step to the next link (cyclically)
                and "random" means that we step to another
                link randomly sampled from the dataset
            simplification_switch: if True, links are
                simplified between states; if False, links
                are not simplified between states (but
                features and rewards are still computed on
                simplified versions), except that the band
                move frameworks remove the Reidemeister I
                kinks a band leaves, since a band cannot act
                on a diagram with a monogon face
            device: the device of the policy network,
                "cpu", "cuda" or "auto"
            mdp: if True, the observation also carries the
                part of the state that the default
                observation leaves out, which makes it a
                Markov state, with its sentinels rewritten by
                env.encode_observation, and train_rl scales
                it with ScaledInputExtractor; see
                env.KnotEnv.observe. A model trained with one
                value cannot be loaded with the other, since
                the observation spaces differ
            old_reward: if True, every framework keeps the
                reward of its get_reward, the reward of the
                models trained before the current one
                existed; if False, every framework uses its
                _reward (env.CrossChangeEnv._reward or
                env.BandMoveEnv._reward), which is meant for
                gamma = 1 and episodes of at most
                REWARD_MAX_ACTIONS actions. What it charges
                is reward_settings below, so a training
                resumed from these parameters keeps the
                reward it started on.
            reward_settings: the settings of that reward
                (env.REWARD_SETTINGS), by name. None means
                the settings of the environment class, which
                create_env then records here, so that
                parameters pickled with a model say which
                reward it was trained on; a dictionary is
                applied to the environment instead, which is
                how a model trained under other settings can
                be given them back by hand
            seed: the master seed of the run these parameters
                belong to. It is a record: nothing reads it,
                the seeding goes through seeding.resolve_seed
                and seeding.derive_seed

        Raises:
            ValueError: if sampling_method is not
                "consecutive" or "random"
        """
        if sampling_method not in ['consecutive', 'random']:
            raise ValueError(f'"{sampling_method}" is not '
                             f'a valid sampling method')
        if device not in ['cpu', 'cuda', 'auto']:
            raise ValueError(f'"{device}" is not '
                             f'a valid device')
        self.max_actions = max_actions
        self.shape = shape
        self.max_twists = max_twists
        self.gamma = gamma
        if features_cls is None:
            features_cls: List[str] = []
        self.features_cls = features_cls
        self.sampling_method = sampling_method
        self.simplification_switch = simplification_switch
        self.device = device
        self.mdp = mdp
        self.old_reward = old_reward
        self.reward_settings = reward_settings
        self.seed = seed

    def __repr__(self) -> str:
        """
        Returns a string representation of the RLParam instance.

        Returns:
            A string representation showing all parameter values.
        """
        return (f"Parameters for RL:\n"
                f"  max_actions={self.max_actions}, \n"
                f"  shape={self.shape}, \n"
                f"  max_twists={self.max_twists}, \n"
                f"  gamma={self.gamma}, \n"
                f"  features_cls={self.features_cls}, \n"
                f"  sampling_method='{self.sampling_method}', \n"
                f"  simplification_switch={self.simplification_switch}, \n"
                f"  mdp={self.mdp}, \n"
                f"  old_reward={self.old_reward}, \n"
                f"  reward_settings={self.reward_settings}, \n"
                f"  seed={self.seed}")


def create_env(framework: str,
               params: RLParam,
               dataset: List[Link] = None,
               verbose: int = 0) -> TimeLimit:
    """
    Creates a TimeLimit-wrapped KnotEnv environment for
    training or testing the RL model.

    Args:
        framework: the type of link invariant we are
            calculating; 'unknotting' means the unknotting
            number, 'splitting' means the splitting number,
            'weak splitting' means the weak splitting
            number, 'unknotting-alg' means the algebraic
            unknotting number, 'ribbon' / 'strong ribbon'
            mean the (strong) ribbon genus, and 'slice' /
            'strong slice' mean the (strong) slice genus
            (the ribbon frameworks plus the unknot_birth
            action)
        params: the parameters for the TimeLimit-wrapped
            KnotEnv environment
        dataset: the dataset given to the KnotEnv
            environment
        verbose: the level of verbosity; if set to 1, then
            the KnotEnv environment prints out the reset and
            step actions it receives; if set to 2, then in
            addition to the action labels, the environment
            also prints the current state and the
            observation in each step

    Returns:
        A TimeLimit-wrapped KnotEnv environment. The reward
        settings of params that this framework has are
        applied to it, and params records the ones in force.

    Raises:
        ValueError: if params.reward_settings holds a name
            that is no reward setting
    """
    if dataset is None:
        dataset = [Link('3_1')]
    env_type = {'unknotting': UnknottingEnv,
                'splitting': SplittingEnv,
                'weak splitting': WeakSplittingEnv,
                'unknotting-alg': UnknottingAlgEnv,
                'ribbon': RibbonEnv,
                'strong ribbon': StrongRibbonEnv,
                'slice': SliceEnv,
                'strong slice': StrongSliceEnv}[framework]
    if not params.old_reward:
        # the ordering that _reward guarantees holds
        # only for gamma = 1 and episodes of at most
        # REWARD_MAX_ACTIONS actions
        if params.gamma != 1:
            warnings.warn(f'old_reward=False with gamma='
                          f'{params.gamma}: a lower answer is '
                          f'guaranteed to dominate only with '
                          f'gamma=1')
        if params.max_actions > REWARD_MAX_ACTIONS:
            warnings.warn(f'old_reward=False with max_actions='
                          f'{params.max_actions} > '
                          f'REWARD_MAX_ACTIONS='
                          f'{REWARD_MAX_ACTIONS}: a lower answer '
                          f'is not guaranteed to dominate path '
                          f'length')
    knot_env = env_type(dataset, params.shape,
                        params.max_twists, params.gamma,
                        params.features_cls,
                        params.sampling_method, verbose,
                        params.simplification_switch,
                        mdp=params.mdp,
                        old_reward=params.old_reward)
    # Parameters that carry reward settings (because they
    # were pickled with a model, or edited by hand) give them
    # to the environment; parameters that carry none record
    # the ones the environment was built with. A setting of
    # the other family of frameworks is dropped, since the
    # same parameters may be used for several frameworks; a
    # name that is no setting at all still raises.
    settings = {name: value
                for name, value in (getattr(params, 'reward_settings', None)
                                    or {}).items()
                if hasattr(knot_env, name) or name not in REWARD_SETTINGS}
    params.reward_settings = knot_env.reward_settings(settings)
    env = TimeLimit(knot_env,
                    max_episode_steps=params.max_actions)
    return env


# Inputs of the policy compressed with a signed logarithm
# instead of divided by a constant, because their values are
# higher (polynomial coefficients reach the tens of thousands
# on large diagrams).
LOG_SCALED_INPUTS = ('alexander_coeffs', 'alexander_poly',
                     'jones_coeffs', 'determinant')
# The signed logarithm maps a magnitude of LOG_SCALE_REF to 1.
LOG_SCALE_REF = 1000.0


def input_divisors(key: str,
                   shape: Tuple[int, ...],
                   n: int,
                   m: int) -> Optional[np.ndarray]:
    """
    The constants ScaledInputExtractor divides an input of
    the policy by. Labels and indices are divided by their
    largest value on a diagram with at most n crossings and
    m components; counts by a cap of the order of their
    usual range; signs and flags by 1.

    Args:
        key: the observation key
        shape: the shape of its array
        n: the largest number of crossings of the
            observation (shape[0] of the environment)
        m: the largest number of link components of the
            observation (shape[1] of the environment)

    Returns:
        An array of shape `shape` of positive divisors, or
        None for a key to compress with the signed logarithm
        instead: the keys of LOG_SCALED_INPUTS and any key
        this function does not know.
    """
    per_column = {
        # rows of (crossing, strand index, sign)
        'band_path': (n, 4, 1),
        # rows of (component label, end actions, initial,
        # current and original component counts)
        'genera_info': (m, n, m, m, m),
    }
    if key in per_column:
        return np.broadcast_to(
            np.array(per_column[key], dtype=float), shape).copy()
    divisor = {
        'PD_code': 2 * n, 'gauss_code': n, 'band_matrix': 3,
        'crossing_signs': 1,
        'component_matrix': m, 'component_ccl': m,
        'num_link_components': m, 'num_connected_components': m,
        'unlinked_unknot_components': m,
        'writhe': n, 'simplified_num_crossings': n,
        'init_num_crossings': n, 'jones_lo': n,
        'linking_matrix': 10, 'ccl_linking_matrix': 10,
        'band_twists': 5, 'total_twists': 10,
        'current_genus': 10, 'crossing_changes': 10,
        'signature': 10, 'mt_bound': 10,
        'seifert_genus_bound': 10, 'seifert_genus': 10,
        'nu': 10, 'tau': 10, 'init_seifert_genus': 10,
        'theta_evals': 1,
    }.get(key)
    if divisor is None and key.endswith('_undefined'):
        divisor = 1
    if divisor is None or key in LOG_SCALED_INPUTS:
        return None
    return np.full(shape, float(divisor))


class ScaledInputExtractor(BaseFeaturesExtractor):
    """
    Features extractor of the policy. It flattens a
    dictionary observation, as SB3's CombinedExtractor does,
    and brings every input to order 1 with a fixed map: a
    division by input_divisors or, where that returns None,
    the signed logarithm
    sign(x) log(1 + |x|) / log(1 + LOG_SCALE_REF).
    Unscaled, labels of up to twice the number of crossings
    saturate the first tanh layer, and the policy stops
    depending on the state. The map has no trainable
    parameters.

    Args:
        observation_space: the dictionary observation space
            of a KnotEnv, which always has the keys PD_code
            and gauss_code
    """

    def __init__(self, observation_space: spaces.Dict):
        n = observation_space['PD_code'].shape[0]
        m = observation_space['gauss_code'].shape[0] - 2 * n
        keys = sorted(observation_space.spaces)
        divisors, log_mask = [], []
        for key in keys:
            shape = observation_space[key].shape
            d = input_divisors(key, shape, n, m)
            log_mask.append(np.full(int(np.prod(shape)), d is None))
            divisors.append(np.ones(int(np.prod(shape)))
                            if d is None else d.ravel())
        divisors = np.concatenate(divisors)
        super().__init__(observation_space,
                         features_dim=int(divisors.size))
        self.keys = keys
        self.register_buffer(
            'divisor', th.as_tensor(divisors, dtype=th.float32))
        self.register_buffer(
            'log_mask', th.as_tensor(np.concatenate(log_mask)))

    def forward(self, observations: Dict[str, th.Tensor]
                ) -> th.Tensor:
        x = th.cat([observations[key].reshape(
                        observations[key].shape[0], -1)
                    for key in self.keys], dim=1)
        compressed = (th.sign(x) * th.log1p(x.abs())
                      / math.log1p(LOG_SCALE_REF))
        return th.where(self.log_mask, compressed,
                        x / self.divisor)


def train_rl(
        framework: str,
        dataset: List[Link],
        training_timesteps: int,
        params: RLParam,
        policy_kwargs: Dict[str, Any] = None,
        num_workers: Optional[int] = None,
        n_steps: int = 2048,
        verbose: int = 0,
        tensorboard_log: Optional[str] = None,
        tb_log_name: str = 'PPO',
        model_kwargs: Dict[str, Any] = None,
        training_kwargs: Dict[str, Any] = None,
        seed: Optional[int] = None
) -> Tuple[MaskablePPO, TimeLimit]:
    """
    Trains a MaskablePPO policy on a dataset of links with
    specified parameters.

    Args:
        framework: the type of link invariant we are
            calculating; 'unknotting' means the unknotting
            number, 'splitting' means the splitting number,
            'weak splitting' means the weak splitting
            number, 'unknotting-alg' means the algebraic
            unknotting number, 'ribbon' means the ribbon
            genus, and 'slice' means the slice genus
        dataset: the list of links we are training our
            policy on
        training_timesteps: the total number of training
            timesteps
        params: the parameters for the KnotEnv environment,
            the TimeLimit wrapper and the MaskablePPO
            algorithm
        policy_kwargs: additional arguments to be passed to
            the policy on creation, which can specify the
            architecture of the neural network (including
            the activation function and the shape of the
            hidden layers); when params.mdp is set,
            features_extractor_class defaults to
            ScaledInputExtractor
        num_workers: the number of parallel environments in
            the SubprocVecEnv
        n_steps: the number of steps to run for each
            environment per worker per update
        verbose: the level of verbosity; if set to 1, then
            the KnotEnv environment prints out the reset and
            step actions it receives; if set to 2, then in
            addition to the action labels, the environment
            also prints the current state and the
            observation in each step
        tensorboard_log: the log location for tensorboard
            (if None, no logging)
        tb_log_name: the name of the run for tensorboard
            logging
        model_kwargs: additional parameters to pass to the
            MaskablePPO constructor, which can include
            custom learning rates and clipping parameters to
            prevent catastrophic forgetting
        training_kwargs: additional parameters to pass to
            MaskablePPO.learn, which may include callbacks
        seed: if given, seeds every random number
            generator with set_all_seeds and passes a
            derived 32-bit seed to MaskablePPO and
            make_vec_env, which reseed the environments at
            their first reset; model_kwargs must then not
            contain a seed

    Returns:
        A pair consisting of the trained MaskablePPO policy
        and the TimeLimit-wrapped KnotEnv environment.
    """
    if params.sampling_method != 'random':
        warnings.warn('random sampling is recommended for '
                      'training RL agents in production '
                      'because it makes the mean reward '
                      'comparable across batches')
    sb3_seed = None
    if seed is not None:
        set_all_seeds(seed)
        # SB3 hands its seed to np.random.seed, which takes
        # 32 bits
        sb3_seed = derive_seed(seed, 'sb3') % 2**32

    def env_fn() -> TimeLimit:
        return create_env(framework, params, dataset, verbose)

    if num_workers is not None:
        env = make_vec_env(
            env_fn, num_workers, seed=sb3_seed,
            vec_env_cls=SubprocVecEnv,
            vec_env_kwargs={'start_method': 'spawn'}
        )
    else:
        env = env_fn()
    if model_kwargs is None:
        model_kwargs = {}
    policy_kwargs = dict(policy_kwargs or {})
    if params.mdp:
        policy_kwargs.setdefault('features_extractor_class',
                                 ScaledInputExtractor)
    model = MaskablePPO('MultiInputPolicy',
                        env,
                        n_steps=n_steps,
                        gamma=params.gamma,
                        verbose=1,
                        tensorboard_log=tensorboard_log,
                        policy_kwargs=policy_kwargs,
                        device = params.device,
                        seed=sb3_seed,
                        **model_kwargs)
    if training_kwargs is None:
        training_kwargs = {}
    model.learn(total_timesteps=training_timesteps,
                tb_log_name=tb_log_name,
                **training_kwargs)
    return model, env


def band_operation_rl(
        model: MaskablePPO,
        env: TimeLimit,
        obs: ObsType,
        mixed_params: Optional[List[float]],
        current_best: int,
        verbose: bool,
        rng: random.Random
) -> Tuple[int,
           List[Tuple[str, float]],
           List[Link],
           List[str]]:
    """
    Given a link, calculates an upper bound of its link
    invariant by attempting to reduce it to a terminal link
    through a sequence of crossing changes or band moves
    predicted by a MaskablePPO policy (or optionally by the
    random walker according to the mixed strategy
    parameters), returning the agent's answer along with the
    list of actions taken and their rewards, the link
    trajectory and the list of random states before each end
    action.

    Args:
        model: the given MaskablePPO policy
        env: the TimeLimit-wrapped KnotEnv environment;
            should be created by create_env, invoked either
            directly or through train_rl
        obs: the initial observation for the current link
        mixed_params: the parameters for the mixed strategy
            agent; the first value is the twist probability,
            the second value is the end probability, the
            third value is the initial probability of using
            the prediction from the random walker, the
            fourth value is the decay of the aforementioned
            probability after a non-end action, the fifth
            value is the decay of the same probability after
            an end action, the sixth value is the minimum
            probability of using the predictions from the
            random walker, independent of any decay, and the
            seventh and final value is the probability that
            the random walker, when in control with no band
            in progress, takes an unknot_birth action (only
            meaningful for the slice frameworks; 0.0
            otherwise); if not given, then only the
            predictions of the RL-based agent are used
        current_best: if we are taking the minimum over
            multiple attempts, we can stop once we know that
            we cannot beat the given current best; if the
            provided value is -1, then we do not stop
            because of this reason
        verbose: whether we are outputting the actions taken
            by the RL-based or mixed agent and their rewards
        rng: the generator of the mixed strategy's random
            draws

    Returns:
        A 4-tuple, consisting of the following
        components:
        1. An upper bound for the link invariant. If the
           agent did not succeed in reducing the link to a
           terminal link, it is -1.
        2. A list of actions that the RL-based or mixed
           agent has taken and their rewards, regardless of
           whether the agent succeeded or not. The length of
           this list is used to determine the number of
           steps that the agent has consumed.
        3. The link trajectory, consisting of the initial
           link and every link generated by an end action.
        4. The states of std/random just before
           Link.simplify, useful for replaying the link
           simplifications of the end actions when verifying
           the results obtained.
    """
    knot_env: KnotEnv = env.unwrapped
    # trivial case: link is terminal
    cur_answer = knot_env.compute_current_answer()
    if knot_env.is_terminal():
        if verbose:
            print(knot_env.terminal_state_message())
        return cur_answer, [], knot_env.link_history, []
    # if the link is not terminal, we cannot possibly beat
    # the current best if it is 1 (for crossing changes) or
    # 0 (for band moves)
    may_discard_birth_components = (
        knot_env.framework in ('slice', 'strong slice') and
        knot_env.cur_state.has_unfused_birth_components())
    if (not may_discard_birth_components and
            current_best != -1 and cur_answer >= current_best -
            knot_env.state_type.beaten_by_offset):
        if verbose:
            print(f'cannot beat current_best={current_best}')
        return -1, [], knot_env.link_history, []
    if mixed_params is not None:
        p_rw = mixed_params[2]
    while True:
        if (mixed_params is not None and
                rng.random() < max(mixed_params[5], p_rw)):
            agent_type = 'RW'
            # Unknot-birth gate: for the slice frameworks, when no band 
            # is in progress, take an unknot_birth with probability p_birth
            # (mixed_params[6]); otherwise sample a normal RW transition.
            # p_birth is 0.0 for the non-slice frameworks
            if (mixed_params[6] > 0.0 and
                    len(knot_env.cur_state.band_path) == 0 and
                    rng.random() < mixed_params[6]):
                label = 'unknot_birth'
            else:
                label = knot_env.cur_state.random_walk_transition(*mixed_params[:2])
            if label is None:
                if verbose:
                    print('run out of legal moves')
                return (-1, knot_env.actions_rewards,
                        knot_env.link_history,
                        knot_env.random_states)
            action = knot_env.label_actions[label]
        else:
            agent_type = 'RL'
            action_masks = get_action_masks(knot_env)
            if not any(action_masks):
                if verbose:
                    print('run out of legal moves')
                return (-1, knot_env.actions_rewards,
                        knot_env.link_history,
                        knot_env.random_states)
            action, _ = model.predict(obs,
                                      action_masks=action_masks)
            label = knot_env.action_labels[action]
        obs, reward, terminated, truncated, _ = env.step(action)
        if verbose:
            print(f'{agent_type}: {label} -> {reward}; ',
                  end='')
        if terminated:
            if knot_env.is_terminal():
                # we have reached a terminal link
                if verbose:
                    print(knot_env.terminal_state_message())
                return (knot_env.compute_current_answer(),
                        knot_env.actions_rewards,
                        knot_env.link_history,
                        knot_env.random_states)
            # we have run into an error state
            if verbose:
                print('run into an error state')
            return (-1, knot_env.actions_rewards,
                    knot_env.link_history,
                    knot_env.random_states)
        cur_answer = knot_env.compute_current_answer()
        if truncated:
            # we have exceeded the maximum number of steps
            # allowed
            if verbose:
                print('exceeded max_actions')
            return (-1, knot_env.actions_rewards,
                    knot_env.link_history,
                    knot_env.random_states)
        # Pure-birth genus may be discarded at termination, so the
        # current total need not be a lower bound for the final answer.
        may_discard_birth_components = (
            knot_env.framework in ('slice', 'strong slice') and
            knot_env.cur_state.has_unfused_birth_components())
        # we are not going to beat the current best
        if (band_get_act_type(label) == 'end' and
                not may_discard_birth_components and
                current_best != -1 and cur_answer >=
                current_best - knot_env.state_type.beaten_by_offset):
            if verbose:
                print(f'cannot beat current_best='
                      f'{current_best}')
            return (-1, knot_env.actions_rewards,
                    knot_env.link_history,
                    knot_env.random_states)
        # apply the decay to p_rw
        if mixed_params is not None:
            if band_get_act_type(label) == 'end':
                p_rw *= mixed_params[4]
            else:
                p_rw *= mixed_params[3]


class MixedStrategyParam:
    """Parameters for the mixed strategy agent."""
    p_twist: float
    p_end: float
    p_rw_range: Tuple[float, float]
    step_decay: float
    end_decay: float
    min_p_rw: float
    p_birth: float

    def __init__(
            self,
            p_twist: float,
            p_end: float,
            p_rw_range: Tuple[float, float] = (0.0, 0.6),
            step_decay: float = 0.9,
            end_decay: float = 0.75,
            min_p_rw: float = 0.06,
            p_birth: float = 0.0
    ):
        """
        Initializes a set of parameters for the mixed
        strategy agent.

        Args:
            p_twist: the twist probability
            p_end: the end probability
            p_rw_range: the range of initial probabilities
                of using the predictions from the random
                walker; the actual initial probability will
                be uniformly sampled from this range
            step_decay: the decay of the probability of
                using the predictions from the random walker
                after a non-end action
            end_decay: the decay of the same probability
                after an end action
            min_p_rw: the minimum probability of using the
                predictions from the random walker, enforced
                after the decay has been applied
            p_birth: the probability that, when the random
                walker is in control and no band is in
                progress, it takes an unknot_birth action;
                only meaningful for the "slice" and "strong
                slice" frameworks

        Raises:
            ValueError: if the given p_rw_range is not a
                valid range of probabilities
        """
        if not 0.0 <= p_rw_range[0] <= p_rw_range[1] <= 1.0:
            raise ValueError(f'{p_rw_range} is not a valid '
                             f'range of probabilities')
        self.p_twist = p_twist
        self.p_end = p_end
        self.p_rw_range = p_rw_range
        self.step_decay = step_decay
        self.end_decay = end_decay
        self.min_p_rw = min_p_rw
        self.p_birth = p_birth

    @staticmethod
    def default(framework: str) -> 'MixedStrategyParam':
        """
        Returns the default parameters for the mixed agent for
        a given framework.

        Args:
            framework: the type of link invariant we are
                calculating; 'unknotting' means the unknotting
                number, 'splitting' means the splitting
                number, 'weak splitting' means the weak
                splitting number, 'unknotting-alg' means the
                algebraic unknotting number, 'ribbon'
                means the ribbon genus, and 'slice' means
                the slice genus

        Returns:
            The default parameters for the mixed agent for the
            given framework.
        """
        p_twist, p_end, p_rw_range, min_p_rw, p_birth, step_decay, end_decay = {
            'unknotting':    (0.6644, 59.5559, (0.7, 1.0),
                              0.0221, 0.0, 0.15, 0.75),
            'ribbon':        (0.0300, 7.1768, (0.9, 1.0),
                              0.0061, 0.0, 0.15, 0.75),
            'slice':         (0.0102, 0.5228, (0.8, 0.9),
                              0.0002, 0.0501, 0.3, 0.75),
            'strong ribbon': (0.0102, 66.5839, (0.75, 1.0),
                              0.0024, 0.0, 0.3, 0.75),
            'strong slice':  (0.2325, 0.5211, (0.7, 1.0),
                              0.0225, 0.0066, 0.3, 0.75),
        }[framework]
        return MixedStrategyParam(
            p_twist, p_end,
            p_rw_range=p_rw_range,
            step_decay=step_decay,
            end_decay=end_decay,
            min_p_rw=min_p_rw,
            p_birth=p_birth
        )


def band_operations_rl(
        model: MaskablePPO,
        env: TimeLimit,
        dataset: List[Link],
        testing_timesteps: int,
        mixed_params: Optional[MixedStrategyParam] = None,
        verbose: bool = False,
        seed: Optional[int] = None,
        prior_results: Optional[List[Tuple[int,
                                           List[Tuple[str, float]],
                                           List[Link],
                                           List[str]]]] = None
) -> List[Tuple[int,
                List[Tuple[str, float]],
                List[Link],
                List[str]]]:
    """
    Given a MaskablePPO policy and a list of links,
    calculates upper bounds of their link invariants by
    attempting to reduce them to a terminal link through
    sequences of crossing changes or band moves predicted by
    the MaskablePPO policy (or optionally by the random
    walker according to the mixed strategy parameters),
    returning the agent's answers for the links along with
    the lists of actions taken and their rewards, the link
    trajectories and the lists of random states before each
    end action.

    Args:
        model: the given MaskablePPO policy
        env: the TimeLimit-wrapped KnotEnv environment;
            should be created by create_env, invoked either
            directly or through train_rl
        dataset: a list of links whose link invariants we
            are trying to calculate
        testing_timesteps: the total number of steps
            allowed, shared by all the links in the dataset
        mixed_params: the parameters for the mixed strategy
            agent; if None, then only predictions from the
            RL agent are used
        verbose: whether we are outputting the actions taken
            by the RL-based or mixed agent and their rewards
        seed: if given, every random draw of the call is
            seeded from it (set_all_seeds, the first reset
            of env, the mixed strategy), so the output is a
            function of the arguments; if None, the draws
            are unseeded
        prior_results: the output of an earlier call on the
            same dataset; if given, the call starts from
            its answers and replaces one only with a lower
            answer, so an evaluation can be split into
            rounds

    Returns:
        A list of 4-tuples for each link in dataset. Their
        meanings are explained in the docstring of
        band_operation_rl.
    """
    knot_env: KnotEnv = env.unwrapped
    original_verbose = knot_env.verbose
    knot_env.verbose = 0
    if prior_results is None:
        answers = [-1] * len(dataset)
        actions_rewards_list: List[List[Tuple[str, float]]] = [[] for _ in range(len(dataset))]
        links_history: List[List[Link]] = [[] for _ in range(len(dataset))]
        random_states_list: List[List[str]] = [[] for _ in range(len(dataset))]
    else:
        answers: List[int] = []
        actions_rewards_list: List[List[Tuple[str, float]]] = []
        links_history: List[List[Link]] = []
        random_states_list: List[List[str]] = []
        for (answer, actions_rewards, link_history, random_states) in prior_results:
            answers.append(answer)
            actions_rewards_list.append(actions_rewards)
            links_history.append(link_history)
            random_states_list.append(random_states)
    reset_seed = None
    if seed is not None:
        set_all_seeds(seed)
        reset_seed = derive_seed(seed, 'env')
    # random.Random(None) seeds itself from the operating
    # system
    rng = random.Random(None if seed is None
                        else derive_seed(seed, 'mixed'))
    steps_remaining = testing_timesteps
    obs, _ = env.reset(seed=reset_seed,
                       options={'dataset': dataset})
    if verbose:
        print(f'reset to link {knot_env.index}: ', end='')
    while steps_remaining > 0:
        cur_link = knot_env.index
        mixed_degree: Optional[List[float]] = None
        if mixed_params is not None:
            mixed_degree = [mixed_params.p_twist,
                            mixed_params.p_end,
                            rng.uniform(*mixed_params.p_rw_range),
                            mixed_params.step_decay,
                            mixed_params.end_decay,
                            mixed_params.min_p_rw,
                            mixed_params.p_birth]
        answer, actions_rewards, link_history, random_states = band_operation_rl(
            model, env, obs, mixed_degree, answers[cur_link], verbose,
            rng)
        if answer != -1 and (answers[cur_link] == -1 or
                             answer < answers[cur_link]):
            answers[cur_link] = answer
            actions_rewards_list[cur_link] = actions_rewards
            links_history[cur_link] = link_history
            random_states_list[cur_link] = random_states
        steps_remaining -= len(actions_rewards) + 1
        obs, _ = env.reset()
        if verbose:
            print(f'reset to link {knot_env.index}: ',
                  end='')
    # the last action is always a reset action, so we need
    # to print an extra newline
    if verbose:
        print()
    knot_env.verbose = original_verbose
    return list(zip(answers, actions_rewards_list,
                    links_history, random_states_list))


def band_operations_rl_worker(
    args: Tuple[
        bytes,              # pickled MaskablePPO
        str,                # framework
        RLParam,            # params to rebuild env
        List[Link],         # dataset shard
        int,                # steps
        Optional[MixedStrategyParam],
        bool,               # verbose
        str,                # device ('cpu' / 'cuda' / 'auto')
        int,                # seed of this shard
        Optional[List[Tuple[int,  # prior results of this shard
                            List[Tuple[str, float]],
                            List[Link],
                            List[str]]]]
    ]
) -> List[Tuple[int,
        List[Tuple[str, float]],
        List[Link],
        List[str]]]:
    """
    Worker entry point for parallel evaluation.

    IMPORTANT: Do NOT pass a live environment across processes.
    Rebuild a fresh env in each worker to avoid pickling/ABI issues
    with C/C++/Nim-backed state. This prevents segfaults stemming
    from invalid pointers after spawn.

    The model is reloaded with an explicit ``device``. The
    shard runs with its own seed, so no two workers share a
    random stream.
    """
    (model_pickle, framework, params, dataset, steps,
     mixed_params, verbose, device, seed, prior_results) = args
    # Rebuild environment locally in the child process
    env_local = create_env(framework, params, dataset, verbose=0)
    # Load model from bytes and bind to the fresh env, on the same
    # device the parent used (NOT SB3's 'auto').
    model = MaskablePPO.load(BytesIO(model_pickle), env_local,
                             device=device)
    return band_operations_rl(model, env_local, dataset, steps,
                              mixed_params=mixed_params,
                              verbose=verbose, seed=seed,
                              prior_results=prior_results)


def env_rebuild_params(env: TimeLimit,
                       seed: int) -> Tuple[str, RLParam]:
    """
    Returns what another process needs to rebuild an
    environment with create_env, since a live environment
    cannot cross processes.

    Args:
        env: the TimeLimit-wrapped KnotEnv environment
        seed: the seed recorded in the parameters

    Returns:
        The framework of env and parameters with its
        settings, including the reward settings in force.
    """
    knot_env: KnotEnv = env.unwrapped
    framework = knot_env.framework
    params = RLParam(
        max_actions=(getattr(env, "_max_episode_steps", None)
                     or (env.spec.max_episode_steps if hasattr(env, 'spec') and env.spec is not None else 50)),
        shape=knot_env.shape,
        max_twists=knot_env.max_twists,
        gamma=knot_env.gamma,
        features_cls=knot_env.features_cls,
        sampling_method=knot_env.sampling_method,
        simplification_switch=knot_env.simplification_switch,
        mdp=knot_env.mdp,
        old_reward=knot_env.old_reward,
        # the workers must charge what this environment
        # charges, whatever it was given
        reward_settings=knot_env.reward_settings(),
        seed=seed
    )
    return framework, params


def band_operations_rl_parallel(
        model: MaskablePPO,
        env: TimeLimit,
        dataset: List[Link],
        testing_timesteps: int,
        num_workers: int,
        mixed_params: Optional[MixedStrategyParam] = None,
        verbose: bool = False,
        seed: Optional[int] = None,
        prior_results: Optional[List[Tuple[int,
                                           List[Tuple[str, float]],
                                           List[Link],
                                           List[str]]]] = None
) -> List[Tuple[int,
                List[Tuple[str, float]],
                List[Link],
                List[str]]]:
    """
    Given a MaskablePPO policy and a list of links,
    calculates upper bounds of their link invariants by
    attempting to reduce them to a terminal link through
    sequences of crossing changes or band moves predicted by
    the MaskablePPO policy (or optionally by the random
    walker according to the mixed strategy parameters), with
    the dataset and total steps split between multiple
    worker processes, returning the agent's answers for the
    links along with the lists of actions taken and their
    rewards, the link trajectories and the lists of random
    states before each end action.

    Args:
        model: the given MaskablePPO policy
        env: the TimeLimit-wrapped KnotEnv environment;
            should be created by create_env, invoked either
            directly or through train_rl
        dataset: a list of links whose link invariants we
            are trying to calculate
        testing_timesteps: the total number of steps
            allowed, shared by all the links in the dataset
        num_workers: the number of worker processes; its
            recommended value is the number of cores that
            can be utilized
        mixed_params: the parameters for the mixed strategy
            agent; if None, then only predictions from the
            RL agent are used
        verbose: whether we are outputting the actions taken
            by the RL-based or mixed agent and their rewards
        seed: shard i of the split runs with
            derive_seed(seed, "shard", i); if None, a seed is
            drawn, so the shards still never share a random
            stream
        prior_results: the output of an earlier call on the
            same dataset, split between the workers with the
            dataset; see band_operations_rl

    Returns:
        A list of 4-tuples for each link in dataset. Their
        meanings are explained in the docstring of
        band_operation_rl.
    """
    master_seed = resolve_seed(seed)
    dataset_steps_per_worker = split_testing_workload(dataset, testing_timesteps, num_workers)
    num_workers = len(dataset_steps_per_worker)
    if prior_results is None:
        prior_results_per_worker = [None] * num_workers
    else:
        cum_sum = 0
        prior_results_per_worker: List[Optional[List[Tuple[int, List[Tuple[str, float]], List[Link], List[str]]]]] = []
        for i in range(num_workers):
            prior_results_per_worker.append(prior_results[cum_sum:cum_sum+len(dataset_steps_per_worker[i][0])])
            cum_sum += len(dataset_steps_per_worker[i][0])

    # Extract framework and params from the provided env to rebuild in workers
    framework, params = env_rebuild_params(env, master_seed)

    # Serialize the model once to bytes
    with BytesIO() as f:
        model.save(f)
        model_pickle = f.getvalue()

    # Reload the model in each worker on the SAME device 
    # the parent used, so the workers don't fall back to 
    # SB3's 'auto' and seize an (unsupported) GPU.
    device = str(getattr(model, 'device', 'cpu'))

    # Spawn worker processes; each rebuilds its own env
    with ProcessPoolExecutor(num_workers, get_context('spawn')) as p:
        worker_outputs = list(p.map(
            band_operations_rl_worker,
            [(model_pickle, framework, params,
              worker_dataset, worker_steps,
              mixed_params, verbose, device,
              derive_seed(master_seed, 'shard', i),
              worker_prior_results)
             for i, ((worker_dataset, worker_steps),
                     worker_prior_results)
             in enumerate(zip(dataset_steps_per_worker,
                              prior_results_per_worker))]
        ))
    return [c for worker_output in worker_outputs
            for c in worker_output]


def band_operations_rl_parallel_worker(
        model_pickle: bytes,
        framework: str,
        params: RLParam,
        device: str,
        dataset: List[Link],
        steps: int,
        num_workers: int,
        connection: Connection,
        mixed_params: Optional[MixedStrategyParam],
        verbose: bool,
        prior_results: Optional[List[Tuple[int,
                                           List[Tuple[str, float]],
                                           List[Link],
                                           List[str]]]],
        seed: int
) -> None:
    """
    Runs one round of
    band_operations_rl_parallel_multiple_rounds in its own
    process and sends the output through connection.

    Args:
        model_pickle: the MaskablePPO policy, saved to bytes
        framework: the framework of the environment
        params: the parameters that rebuild the environment
            with create_env
        device: the device the policy is loaded on, the one
            of the parent's policy
        dataset: a list of links whose link invariants we
            are trying to calculate
        steps: the steps of this round
        num_workers: the number of worker processes
        connection: the sending end of a pipe to the parent
        mixed_params: the parameters for the mixed strategy
            agent, or None
        verbose: whether we are outputting the actions taken
            by the RL-based or mixed agent and their rewards
        prior_results: the output of the previous round, or
            None
        seed: the seed of this round
    """
    env = create_env(framework, params, dataset, verbose=0)
    model = MaskablePPO.load(BytesIO(model_pickle), env,
                             device=device)
    connection.send(band_operations_rl_parallel(
        model, env, dataset, steps, num_workers,
        mixed_params=mixed_params, verbose=verbose,
        seed=seed, prior_results=prior_results))
    connection.close()


def band_operations_rl_parallel_multiple_rounds(
        model: MaskablePPO,
        env: TimeLimit,
        dataset: List[Link],
        testing_timesteps: int,
        num_workers: int,
        mixed_params: Optional[MixedStrategyParam] = None,
        verbose: bool = False,
        prior_results: Optional[List[Tuple[int,
                                           List[Tuple[str, float]],
                                           List[Link],
                                           List[str]]]] = None,
        max_steps_per_round: int = 1000000,
        seed: Optional[int] = None
) -> List[Tuple[int,
                List[Tuple[str, float]],
                List[Link],
                List[str]]]:
    """
    Runs band_operations_rl_parallel in rounds of at most
    max_steps_per_round steps, each in a new process, every
    round starting from the answers of the previous one.
    Memory that the compiled modules do not free is given
    back when the process of a round exits, so a long
    evaluation does not run out of it.

    Args:
        model: the given MaskablePPO policy
        env: the TimeLimit-wrapped KnotEnv environment;
            should be created by create_env, invoked either
            directly or through train_rl
        dataset: a list of links whose link invariants we
            are trying to calculate
        testing_timesteps: the total number of steps
            allowed, shared by all the links in the dataset
            and split between the rounds
        num_workers: the number of worker processes of each
            round
        mixed_params: the parameters for the mixed strategy
            agent; if None, then only predictions from the
            RL agent are used
        verbose: whether we are outputting the actions taken
            by the RL-based or mixed agent and their rewards
        prior_results: the output of an earlier call on the
            same dataset, where the first round starts; see
            band_operations_rl
        max_steps_per_round: the steps of every round but
            the last; lowering it bounds the memory a round
            can accumulate, at the cost of starting the
            worker processes more often
        seed: round r runs with derive_seed(seed, "round",
            r); if None, a seed is drawn, so no two rounds
            replay the same episodes

    Returns:
        A list of 4-tuples for each link in dataset. Their
        meanings are explained in the docstring of
        band_operation_rl.

    Raises:
        ValueError: if max_steps_per_round is not positive
        RuntimeError: if the process of a round exits
            before sending its output, for example when it
            is killed for running out of memory
    """
    if max_steps_per_round <= 0:
        raise ValueError(f'max_steps_per_round '
                         f'{max_steps_per_round} is not '
                         f'positive')
    master_seed = resolve_seed(seed)
    framework, params = env_rebuild_params(env, master_seed)
    with BytesIO() as f:
        model.save(f)
        model_pickle = f.getvalue()
    device = str(getattr(model, 'device', 'cpu'))
    round_steps_list = [max_steps_per_round] * (testing_timesteps // max_steps_per_round)
    if testing_timesteps % max_steps_per_round != 0:
        round_steps_list.append(testing_timesteps % max_steps_per_round)
    context = get_context('spawn')
    cur_results = prior_results
    for r, round_steps in enumerate(round_steps_list):
        receiver, sender = context.Pipe(duplex=False)
        p = context.Process(
            target=band_operations_rl_parallel_worker,
            args=(model_pickle, framework, params, device,
                  dataset, round_steps, num_workers, sender,
                  mixed_params, verbose, cur_results,
                  derive_seed(master_seed, 'round', r)))
        p.start()
        # with the parent's sending end closed, recv fails
        # if the round exits before sending all its output;
        # the output is read before the join, since the
        # round cannot exit while an output larger than the
        # pipe buffer is unread
        sender.close()
        try:
            cur_results = receiver.recv()
        except (EOFError, OSError):
            p.join()
            raise RuntimeError(f'round {r} exited with code '
                               f'{p.exitcode} before sending '
                               f'its output') from None
        finally:
            receiver.close()
        p.join()
    return cur_results
